import { useEffect, useRef, useState } from 'react';
import { Link, NavLink, Outlet, useLocation } from 'react-router';
import { Menu, X } from 'lucide-react';
import clsx from 'clsx';
import { Wordmark } from '../../components/Wordmark';
import { useSession, useSignOut } from '../../lib/session';
import { useInstitution } from '../../lib/institution';

export function DemoStrip() {
  const inst = useInstitution();
  const ref = useRef<HTMLDivElement>(null);
  // Publish the strip's height so full-viewport layouts can subtract it.
  useEffect(() => {
    const el = ref.current;
    const root = document.documentElement;
    if (!el) {
      root.style.setProperty('--demo-strip-h', '0px');
      return;
    }
    const ro = new ResizeObserver(() => root.style.setProperty('--demo-strip-h', `${el.offsetHeight}px`));
    ro.observe(el);
    return () => {
      ro.disconnect();
      root.style.setProperty('--demo-strip-h', '0px');
    };
  }, [inst?.isDemo]);
  if (!inst?.isDemo) return null;
  return (
    <div ref={ref} className="border-b border-line bg-ink-900 px-[var(--gutter)] py-1.5 text-center text-[11.5px] text-paper-3">
      <span className="kicker mr-2 !text-[10px] text-warn">Demo</span>
      <span className="sm:hidden">Sample data — not official {inst.shortName} records.</span>
      <span className="max-sm:hidden">Sample events, people and attendance generated by the seed script — not official {inst.shortName} records.</span>
    </div>
  );
}

const linkCls = ({ isActive }: { isActive: boolean }) =>
  clsx('relative py-1 text-sm transition-colors duration-[var(--dur-fast)]', isActive ? 'text-paper' : 'text-paper-2 hover:text-paper');

export function PublicLayout() {
  const { user, hasWorkspace } = useSession();
  const signOut = useSignOut();
  const location = useLocation();
  const home = location.pathname === '/';
  const [open, setOpen] = useState(false);
  useEffect(() => setOpen(false), [location.pathname]);

  const nav = (
    <>
      <NavLink to="/events" className={linkCls}>
        Events
      </NavLink>
      {user && (
        <NavLink to="/me" end className={linkCls}>
          My events
        </NavLink>
      )}
      {hasWorkspace && (
        <NavLink to="/workspace" className={linkCls}>
          Workspace
        </NavLink>
      )}
      {user ? (
        <button type="button" onClick={signOut} className="py-1 text-left text-sm text-paper-3 hover:text-paper">
          Sign out
        </button>
      ) : (
        <>
          <NavLink to="/login" className={linkCls}>
            Sign in
          </NavLink>
          <Link to="/signup" className="rounded-[var(--radius-sm)] border border-line-strong px-3 py-1.5 text-sm text-paper hover:border-paper-3">
            Create account
          </Link>
        </>
      )}
    </>
  );

  return (
    <div className="flex min-h-dvh flex-col">
      <DemoStrip />
      <header
        className={clsx('z-40 px-[var(--gutter)]', home ? 'absolute inset-x-0 pt-3' : 'sticky top-0 border-b border-line bg-ink-950/90 backdrop-blur-md')}
        style={home ? { top: 'var(--demo-strip-h, 0px)' } : undefined}
      >
        <div className={clsx('mx-auto flex h-14 max-w-[1400px] items-center justify-between')}>
          <Link to="/" aria-label="CAMPUSFLOW home">
            <Wordmark />
          </Link>
          <nav aria-label="Main" className="hidden items-center gap-6 md:flex">
            {nav}
          </nav>
          <button type="button" className="-mr-2 p-2 text-paper-2 md:hidden" aria-label={open ? 'Close menu' : 'Open menu'} aria-expanded={open} onClick={() => setOpen((v) => !v)}>
            {open ? <X className="size-5" /> : <Menu className="size-5" />}
          </button>
        </div>
        {open && (
          <nav aria-label="Main" className="mx-[calc(var(--gutter)*-1)] flex animate-rise flex-col gap-3 border-y border-line bg-ink-900 px-[var(--gutter)] py-5 md:hidden">
            {nav}
          </nav>
        )}
      </header>
      <div className="flex-1">
        <Outlet />
      </div>
      <Footer />
    </div>
  );
}

function Footer() {
  const inst = useInstitution();
  return (
    <footer className="mt-24 border-t border-line px-[var(--gutter)] py-10 text-sm text-paper-3">
      <div className="mx-auto flex max-w-[1400px] flex-col justify-between gap-6 sm:flex-row sm:items-end">
        <div className="space-y-2">
          <Wordmark />
          <p className="max-w-sm">Discovery, registration, teams, payments, tickets and check-in for {inst?.name ?? 'your campus'}.</p>
        </div>
        <div className="flex flex-wrap gap-x-6 gap-y-2">
          <Link to="/events" className="hover:text-paper">
            All events
          </Link>
          <Link to="/workspace" className="hover:text-paper">
            Organizer workspace
          </Link>
          <Link to="/join" className="hover:text-paper">
            Join a team with a code
          </Link>
        </div>
      </div>
    </footer>
  );
}
